ROOT = Path(__file__).resolve().parents[1]


def swap_meta(html: str, title: str, desc: str, og: str | None = None) -> str:
    ot = og or title
    html = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", html, count=1, flags=re.S)
    html = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{desc}">', html, count=1)
    html = re.sub(r'<meta property="og:title" content="[^"]*">', f'<meta property="og:title" content="{ot}">', html, count=1)
    html = re.sub(r'<meta property="og:description" content="[^"]*">', f'<meta property="og:description" content="{desc}">', html, count=1)
    html = re.sub(r'<meta name="twitter:title" content="[^"]*">', f'<meta name="twitter:title" content="{ot}">', html, count=1)
    html = re.sub(r'<meta name="twitter:description" content="[^"]*">', f'<meta name="twitter:description" content="{desc}">', html, count=1)
    return html


def apply(path: Path, title: str, desc: str, swaps: list[tuple[str, str]], og: str | None = None) -> None:
    html = path.read_text(encoding="utf-8")
    html = swap_meta(html, title, desc, og)
    for a, b in sorted(swaps, key=lambda x: len(x[0]), reverse=True):
        html = html.replace(a, b)
    # founder TODO marker for non-IT about
    if path.name == "about.html" and "TODO: tradurre bio founder" not in html:
        html = html.replace(
            '<section id="founder">',
            '<!-- TODO: tradurre bio founder -->\n<section id="founder">',
            1,
        )
    path.write_text(html, encoding="utf-8")
    print("patched", path)


